#include <stdio.h>
#include <stdlib.h>
#include <omp.h>
#include <time.h>

#define N 5

int main() {
    int a[N], square[N];
    int i;

    #pragma omp parallel
    {
        #pragma omp single
        {
            printf("Array generated by thread %d\n", omp_get_thread_num());

            srand(time(NULL));

            for(i = 0; i < N; i++) {
                a[i] = rand() % 100;
                printf("a[%d] = %d\n", i, a[i]);
            }
        }

        #pragma omp barrier

        #pragma omp for
        for(i = 0; i < N; i++) {
            square[i] = a[i] * a[i];

            printf("Element %d processed by thread %d\n",
                   i, omp_get_thread_num());
        }
    }

    printf("\nArray of squares:\n");
    for(i = 0; i < N; i++) {
        printf("%d ", square[i]);
    }

    printf("\n");

    return 0;
}

